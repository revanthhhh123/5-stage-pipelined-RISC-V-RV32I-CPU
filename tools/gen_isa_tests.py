#!/usr/bin/env python3
"""
gen_isa_tests.py - directed, self-checking ISA tests (tests/generated/*.s)

Expected values are computed here with plain Python integer arithmetic,
independently of both the RTL and the ISS.  Each generated program ends with
x31 = 1 on success; any failure jumps to `fail` which leaves x31 = 0xBAD.
"""
import os

M = 0xFFFFFFFF
def s32(v): v &= M; return v - (1 << 32) if v & 0x80000000 else v
def hexs(v): return '0x%x' % (v & M)

CORNER = [0, 1, M, 0x7FFFFFFF, 0x80000000]
IMMS = [-2048, -1, 0, 1, 2047, 0x555]

R_MODEL = {
    'add':  lambda a, b: a + b,           'sub':  lambda a, b: a - b,
    'sll':  lambda a, b: a << (b & 31),   'srl':  lambda a, b: a >> (b & 31),
    'sra':  lambda a, b: s32(a) >> (b & 31),
    'slt':  lambda a, b: int(s32(a) < s32(b)), 'sltu': lambda a, b: int(a < b),
    'xor':  lambda a, b: a ^ b,           'or':   lambda a, b: a | b,
    'and':  lambda a, b: a & b,
}
I_MODEL = {'addi': R_MODEL['add'], 'slti': R_MODEL['slt'], 'sltiu': R_MODEL['sltu'],
           'xori': R_MODEL['xor'], 'ori': R_MODEL['or'], 'andi': R_MODEL['and']}
SH_MODEL = {'slli': R_MODEL['sll'], 'srli': R_MODEL['srl'], 'srai': R_MODEL['sra']}
B_MODEL = {'beq': lambda a, b: a == b, 'bne': lambda a, b: a != b,
           'blt': lambda a, b: s32(a) < s32(b), 'bge': lambda a, b: s32(a) >= s32(b),
           'bltu': lambda a, b: a < b, 'bgeu': lambda a, b: a >= b}


class T:
    def __init__(self, title):
        self.l = ['# %s (auto-generated by tools/gen_isa_tests.py)' % title, '# CHECK x31 1']
        self.n = 0

    def add(self, s): self.l.append('        ' + s)
    def lab(self, s): self.l.append(s + ':')

    def check(self, got_reg, expected):
        self.n += 1
        self.add('li   t3, %s' % hexs(expected))
        self.add('beq  %s, t3, ok%d' % (got_reg, self.n))
        self.add('j    fail')
        self.lab('ok%d' % self.n)

    def finish(self):
        self.add('li   x31, 1')
        self.add('ecall')
        self.lab('fail')
        self.add('li   x31, 0xBAD')
        self.add('ecall')
        return '\n'.join(self.l) + '\n'


def gen_alu_r():
    t = T('R-type ALU instructions')
    for op, f in R_MODEL.items():
        for a in CORNER:
            for b in CORNER + [5, 31, 32]:
                t.add('li   t0, %s' % hexs(a)); t.add('li   t1, %s' % hexs(b))
                t.add('%-4s t2, t0, t1' % op); t.check('t2', f(a, b) & M)
    return t.finish()


def gen_alu_i():
    t = T('I-type ALU instructions (incl. shifts, LUI, AUIPC)')
    for op, f in I_MODEL.items():
        for a in CORNER:
            for imm in IMMS:
                t.add('li   t0, %s' % hexs(a))
                t.add('%-5s t2, t0, %d' % (op, imm)); t.check('t2', f(a, imm & M) & M)
    for op, f in SH_MODEL.items():
        for a in CORNER + [0xF0F0F0F0]:
            for sh in (0, 1, 5, 15, 31):
                t.add('li   t0, %s' % hexs(a))
                t.add('%-4s t2, t0, %d' % (op, sh)); t.check('t2', f(a, sh) & M)
    for imm20 in (0, 1, 0xABCDE, 0xFFFFF, 0x80000):
        t.add('lui  t2, %d' % imm20); t.check('t2', (imm20 << 12) & M)
    for imm20 in (0, 1, 0x12):
        t.lab('au%d' % imm20)
        t.add('auipc t2, %d' % imm20)
        t.add('la   t0, au%d' % imm20)
        t.add('li   t1, %s' % hexs(imm20 << 12))
        t.add('add  t0, t0, t1')
        t.n += 1
        t.add('beq  t2, t0, ok%d' % t.n); t.add('j    fail'); t.lab('ok%d' % t.n)
    # x0 must ignore writes
    t.add('li   t0, 123'); t.add('add  x0, t0, t0'); t.add('addi t2, x0, 0'); t.check('t2', 0)
    return t.finish()


def gen_mem():
    t = T('Load/store: all widths, all byte offsets, sign/zero extension')
    t.add('la   s0, scratch')
    words = [0x80FF7F01, 0x12345678, 0xF0E1D2C3, 0x00008001]
    for i, w in enumerate(words):
        t.add('li   t0, %s' % hexs(w)); t.add('sw   t0, %d(s0)' % (4 * i))
    img = b''.join(w.to_bytes(4, 'little') for w in words)
    for off in range(16):
        b = img[off]
        t.add('lb   t2, %d(s0)' % off);  t.check('t2', ((b ^ 0x80) - 0x80) & M)
        t.add('lbu  t2, %d(s0)' % off);  t.check('t2', b)
    for off in range(0, 16, 2):
        h = int.from_bytes(img[off:off + 2], 'little')
        t.add('lh   t2, %d(s0)' % off);  t.check('t2', ((h ^ 0x8000) - 0x8000) & M)
        t.add('lhu  t2, %d(s0)' % off);  t.check('t2', h)
    for i, w in enumerate(words):
        t.add('lw   t2, %d(s0)' % (4 * i)); t.check('t2', w)
    # sub-word stores must only touch their own bytes
    t.add('li   t0, 0xAABBCCDD'); t.add('sw   t0, 32(s0)')
    t.add('li   t1, 0x11223344')
    ref = bytearray(0xAABBCCDD.to_bytes(4, 'little'))
    for off, op, n in [(0, 'sb', 1), (3, 'sb', 1), (1, 'sb', 1), (2, 'sh', 2), (0, 'sh', 2), (2, 'sb', 1)]:
        t.add('%s   t1, %d(s0)' % (op, 32 + off))
        ref[off:off + n] = (0x11223344 & ((1 << (8 * n)) - 1)).to_bytes(n, 'little')
        t.add('lw   t2, 32(s0)'); t.check('t2', int.from_bytes(ref, 'little'))
    # store immediately followed by load (same address) and load-use chain
    t.add('li   t0, 0x5A5A1234'); t.add('sw   t0, 48(s0)'); t.add('lw   t2, 48(s0)')
    t.add('addi t2, t2, 1'); t.check('t2', 0x5A5A1235)
    t.add('lw   t4, 48(s0)'); t.add('sw   t4, 52(s0)'); t.add('lw   t2, 52(s0)'); t.check('t2', 0x5A5A1234)
    s = t.finish()
    return s + '.data\nscratch: .space 64\n'


def gen_branch():
    t = T('Branches (all 6 types, taken/not-taken), JAL, JALR')
    for op, f in B_MODEL.items():
        for a in CORNER:
            for b in CORNER:
                t.n += 1; n = t.n
                t.add('li   t0, %s' % hexs(a)); t.add('li   t1, %s' % hexs(b))
                t.add('li   t2, 0')
                t.add('%-4s t0, t1, tk%d' % (op, n))
                t.add('j    done%d' % n)
                t.lab('tk%d' % n); t.add('li   t2, 1')
                t.lab('done%d' % n)
                t.add('li   t3, %d' % int(f(a, b)))
                t.add('beq  t2, t3, ok%d' % n); t.add('j    fail'); t.lab('ok%d' % n)
    for k in range(4):   # JAL link value
        t.n += 1; n = t.n
        t.add('jal  t0, jt%d' % n); t.lab('af%d' % n); t.add('j    fail')
        t.lab('jt%d' % n); t.add('la   t1, af%d' % n)
        t.add('beq  t0, t1, ok%d' % n); t.add('j    fail'); t.lab('ok%d' % n)
    for bit in (0, 1):   # JALR link value + bit0 clearing
        t.n += 1; n = t.n
        t.add('la   t1, jr%d' % n)
        if bit: t.add('addi t1, t1, 1')
        t.add('jalr t0, 0(t1)'); t.lab('af%d' % n); t.add('j    fail')
        t.lab('jr%d' % n); t.add('la   t2, af%d' % n)
        t.add('beq  t0, t2, ok%d' % n); t.add('j    fail'); t.lab('ok%d' % n)
    # branch directly after a dependent ALU op and after a load (forwarding into branch)
    t.add('la   s0, bdata'); t.add('li   t0, 7'); t.add('sw   t0, 0(s0)')
    t.add('lw   t1, 0(s0)'); t.add('beq  t1, t0, okA'); t.add('j    fail'); t.lab('okA')
    t.add('addi t1, t0, 1'); t.add('bne  t1, t0, okB'); t.add('j    fail'); t.lab('okB')
    t.add('addi t2, t0, 0'); t.add('addi t3, t2, 0'); t.add('blt  t0, t1, okC'); t.add('j    fail'); t.lab('okC')
    return t.finish() + '.data\nbdata: .word 0\n'


if __name__ == '__main__':
    d = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'tests', 'generated')
    os.makedirs(d, exist_ok=True)
    for name, fn in [('isa_alu_r', gen_alu_r), ('isa_alu_i', gen_alu_i),
                     ('isa_mem', gen_mem), ('isa_branch', gen_branch)]:
        open(os.path.join(d, name + '.s'), 'w').write(fn())
        print('generated', name + '.s')
